"""One research brief: the record of everything researched about an entity, and the page that serves it.

Rendering is pure; `build` reads the published brief and merges every research row into it, so a fact
no later run found, and a fact with no column, is never dropped.
"""

from __future__ import annotations

import json
import re
from typing import Any

from app.ingest.expectations import CONCEPT_TITLES
from app.ingest.research_records import TYPED_SINCE, to_inr
from app.ingest.source_guards import is_private_source
from app.ingest.taxonomy import VOCABULARY
from app.integrations import storage

STAMP = "<!-- Generated by `make client-docs`. Do not edit inside the markers. -->"
# Every signed-in user can open a brief, so private findings and the summary written from them stay out.
PRIVATE_NOTE = ("This research also read private sources (staff datasets or the organisation's own documents). "
                "Their findings, and the summary written from them, are not shown here.")


def _crore(value: Any) -> str:
    """INR is what we store; crore is what a reader thinks in."""
    try:
        n = float(value)
    except (TypeError, ValueError):
        return str(value)
    return f"₹{n / 10_000_000:,.2f} cr" if n >= 10_000_000 else f"₹{n:,.0f}"


def _money(m: dict[str, Any] | None) -> str | None:
    """A Money finding, printed as the source wrote it and as INR."""
    inr = to_inr(m)
    if inr is None:
        return None
    return f"{_crore(inr)} ({m['text']})"


def _place(f: dict[str, Any]) -> str | None:
    bits = [b for b in (f.get("district"), f.get("state")) if b]
    return ", ".join(bits) or None


_EVIDENCE = frozenset({"concept", "evidence", "source_url", "source_name", "confidence", "basis", "page"})


def _join(*bits: Any) -> str:
    return " · ".join(str(b) for b in bits if b)


# Field 4's split, in words. A funder that only restates Rule 4 has set no
# bar of its own, and the brief has to say so rather than listing three
# conditions as if the funder wrote them.
_ELIGIBILITY_KINDS = {
    "statutory_restatement": "restates the statutory minimum",
    "own_bar": "its own bar",
    "disqualifier": "DISQUALIFIER",
}

# Concepts saved before 0031. Rendered so old research keeps its facts on the page; never promoted
# as themselves (promote.funder_from folds `identifier` into the funder record).
LEGACY_TITLES: dict[str, str] = {
    "identifier": "Registrations and identifiers (saved before 0031)",
    "funder_eligibility": "Eligibility it sets for applicants (saved before 0031)",
    "grant": "Grants (saved before 0034)",
}


def headline(f: dict[str, Any]) -> str:
    """One line per finding, from the typed fields of its concept."""
    # A v1 finding is a flat label/value pair and has no typed fields to read.
    # extra="forbid" means a v2 finding can never carry a label, so this is an
    # exact test of which shape arrived, not a guess.
    if "label" in f:
        return _join(f.get("label"), f.get("value"))
    concept = f.get("concept")
    if concept == "identity":
        return _join(f.get("name"), f.get("funder_type"), f.get("legal_form"), f.get("website"),
                     f"founded {f['founded_year']}" if f.get("founded_year") else None,
                     f"part of {f['parent_name']}" if f.get("parent_name") else None,
                     f.get("registered_address"))
    if concept == "identifier":
        return f"{f['id_type'].upper()} {f['id_value']}"
    if concept == "csr_year":
        money = {k: _money(f.get(k)) for k in
                 ("prescribed_csr", "total_spent", "spent_on_projects", "average_net_profit",
                  "unspent_transferred", "excess_spent", "local_area_spent", "admin_overheads",
                  "impact_assessment_cost")}
        return _join(*(f"{k.replace('_', ' ')} {v}" for k, v in money.items() if v)) or "recorded"
    if concept == "csr_spend":
        what = f.get("project_name") or f.get("sector") or "aggregate"
        count = f"{f['project_count']} projects" if f.get("project_count") else None
        label = "/".join(b for b in (f.get("domain"), f.get("theme")) if b) or None
        return _join(what, _money(f.get("amount")), _place(f), count, f.get("partner_name"),
                     f"{label} (inferred)" if label else None)
    if concept == "footprint":
        return _join(_place(f) or f.get("name_as_printed"), f.get("program_name"))
    if concept == "stated_geography":
        return _join(_place(f), f.get("role"))
    if concept == "partner":
        return _join(f.get("partner_name"), f.get("project_name"), _money(f.get("amount")),
                     f.get("relationship_status"), f.get("partner_kind"), f.get("program_name"))
    if concept == "programme_spend":
        return _join(f.get("program_name"), _money(f.get("amount")), "the funder's own figure",
                     "/".join(b for b in (f.get("domain"), f.get("theme")) if b))
    if concept == "program":
        dates = "–".join(str(d) for d in (f.get("start_date"), f.get("end_date")) if d)
        return _join(f.get("name"), f.get("kind"), f.get("status"), dates or None,
                     f"under {f['parent_name']}" if f.get("parent_name") else None)
    if concept == "grant":
        return _join(f.get("recipient_name"), f.get("title"), _money(f.get("amount")),
                     f.get("status"))
    if concept == "metric":
        value = _join(f.get("value") if f.get("value") is not None else None, f.get("unit"))
        return _join(f.get("name"), value,
                     f"target {f['target']}" if f.get("target") is not None else None,
                     f.get("stage"), f.get("period"), _place(f))
    if concept == "contact":
        return _join(f.get("name"), f.get("role"), f.get("kind"))
    if concept == "document":
        return _join(f.get("title"), f.get("doc_type"), f.get("as_of"))
    if concept == "rfp":
        band = [_money(f.get("amount_min")), _money(f.get("amount_max"))]
        return _join(
            f.get("title"),
            f.get("sector"),
            _place(f),
            " to ".join(b for b in band if b) or None,
            f"closes {f['deadline']}" if f.get("deadline") else None,
            None if f.get("status", "open") == "open" else f.get("status"),
            f"{len(f['eligibility'])} eligibility rules" if f.get("eligibility") else None,
        )
    if concept == "eligibility_guideline":
        if f.get("not_stated"):
            return _join(f.get("title"), "states no eligibility")
        return _join(f.get("title"), *(
            f"{label}: {f[key][:160]}" for key, label in (
                ("statutory_restatement", "restates the statutory minimum"),
                ("own_bar", "its own bar"), ("disqualifiers", "DISQUALIFIERS"))
            if f.get(key)))
    if concept == "funder_eligibility":
        # Research saved before 0031. The kind leads, because "restates the law" and "sets its own bar"
        # read completely differently to a fundraiser and the criterion text
        # alone does not say which it is.
        return _join(_ELIGIBILITY_KINDS.get(f.get("kind"), f.get("kind")),
                     f.get("criterion"), f.get("notes"))
    if concept == "org_identity":
        return _join(f.get("name"), f.get("org_kind"), f.get("legal_form"),
                     f"registered {f['registration_date']}" if f.get("registration_date") else None,
                     f"part of {f['parent_name']}" if f.get("parent_name") else None,
                     f.get("registered_address"))
    if concept == "org_identifier":
        number = f.get("id_value") or (f"application {f['application_ref']}" if f.get("application_ref") else None)
        tier = f"{f.get('evidence_tier')} ({f['source_type']})" if f.get("source_type") else None
        return _join(f["id_type"].upper(), number, f.get("status"),
                     f"valid until {f['valid_until']}" if f.get("valid_until") else None, tier)
    if concept == "org_financials":
        money = {k: _money(f.get(k)) for k in
                 ("total_income", "program_spend", "non_program_spend", "foreign_contribution")}
        audited = {True: "audited", False: "unaudited"}.get(f.get("is_audited"))
        return _join(*(f"{k.replace('_', ' ')} {v}" for k, v in money.items() if v),
                     audited) or "recorded"
    if concept == "org_location":
        return _join(_place(f), f.get("role"), f.get("program_name"))
    # A concept with no branch lands here and prints its raw fields. Every one
    # has a branch; this is what a new one looks like until it gets its own.
    return _join(*(v for k, v in f.items() if k not in _EVIDENCE and v is not None))


# Sections in the order the entity-record skill asks its questions, per kind of organisation.
ORDER: dict[str, tuple[str, ...]] = {
    "org": ("org_identity", "org_identifier", "org_financials", "org_location", "program", "metric",
            "partner", "contact", "document"),
    "funder": ("identity", "eligibility_guideline", "csr_year", "csr_spend", "programme_spend", "footprint",
               "stated_geography", "partner", "program", "metric", "rfp", "contact", "document"),
}

# What makes two findings the same fact across runs; a concept not named here keys on its headline.
_SAME_FACT: dict[str, tuple[str, ...]] = {
    "identity": (), "org_identity": (),
    "identifier": ("id_type",), "org_identifier": ("id_type",),
    "csr_year": ("fiscal_year",), "org_financials": ("fiscal_year",),
    "program": ("name",),
    "partner": ("partner_name", "project_name", "fiscal_year"),
    "programme_spend": ("program_name", "fiscal_year"),
    "csr_spend": ("project_name", "sector", "state", "district", "program_name", "fiscal_year"),
    "footprint": ("state", "district", "name_as_printed", "program_name", "fiscal_year"),
    "stated_geography": ("state", "district", "role"),
    "org_location": ("state", "district", "role", "program_name"),
    "metric": ("name", "period", "program_name"),
    "contact": ("name", "role"),
    "document": ("title", "source_url"),
    "rfp": ("title",),
    "eligibility_guideline": ("title",),
}


def _norm(v: Any) -> str:
    return str(v or "").strip().lower()


def fact_key(f: dict[str, Any]) -> tuple:
    concept = f.get("concept") or f"v1:{_norm(f.get('label'))}"
    fields = _SAME_FACT.get(concept)
    if fields is None:
        return concept, _norm(headline(f)), _norm(f.get("fiscal_year"))
    return (concept, *(_norm(f.get(k)) for k in fields))


def _json_list(value: Any) -> list[dict[str, Any]]:
    return value if isinstance(value, list) else json.loads(value or "[]")


def _findings(row: dict[str, Any]) -> list[dict[str, Any]]:
    return _json_list(row["findings"])


_TIER = {"evidenced": 2, "claimed": 1}
_CONFIDENCE = {"high": 3, "medium": 2, "low": 1}


def _strength(group: list[dict[str, Any]]) -> tuple[int, int]:
    return max((_TIER.get(f.get("evidence_tier"), 1), _CONFIDENCE.get(f.get("confidence"), 0)) for f in group)


def merge_findings(rows: list[dict[str, Any]], prior: list[dict[str, Any]] = ()) -> list[dict[str, Any]]:
    """Every fact any run found, once: a later run's replaces an earlier one unless the earlier source is stronger.

    `prior` is the brief's own facts, laid down before the rows (oldest first); a wrong_entity row is another
    organisation and adds nothing.
    """
    by_key: dict[tuple, list[dict[str, Any]]] = {}
    runs = [list(prior), *(_findings(r) for r in rows if r.get("status") != "wrong_entity")]
    for findings in runs:
        mine: dict[tuple, list[dict[str, Any]]] = {}
        for f in findings:
            mine.setdefault(fact_key(f), []).append(f)
        for key, group in mine.items():
            if key not in by_key or _strength(group) >= _strength(by_key[key]):
                by_key[key] = group
    return [f for group in by_key.values() for f in group]


# A fact's typed fields ride in an HTML comment the page strips; "--" is escaped so no value can close it.
_BLOCK = re.compile(r"<!-- (fact|unplaced) (.*?) -->")
# What promotion did with a fact, kept in its block: {"state": ..., "row": ..., "reason": ...}.
STATE = "catalog"


def _block(kind: str, data: dict[str, Any]) -> str:
    body = json.dumps(data, ensure_ascii=False, default=str).replace("--", "\\u002d\\u002d")
    return f"<!-- {kind} {body} -->"


def record(markdown: str | None) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """The facts and the unplaced facts a brief holds, read back from its blocks."""
    facts: list[dict[str, Any]] = []
    unplaced: list[dict[str, Any]] = []
    for kind, body in _BLOCK.findall(markdown or ""):
        try:
            data = json.loads(body)
        except ValueError:
            continue
        (facts if kind == "fact" else unplaced).append(data)
    return facts, unplaced


def _merge_unplaced(*lists: Any) -> list[dict[str, Any]]:
    """Every unplaced fact once, the newest copy of each (field, value)."""
    out: dict[tuple, dict[str, Any]] = {}
    for items in lists:
        for u in items:
            out[(_norm(u.get("field")), _norm(u.get("value")))] = u
    return [u for u in out.values() if not is_private_source(u.get("source_url"))]


_GAP_LABELS = {"not_stated": "Not stated", "blocked": "Could not read", "not_reached": "Not reached"}


def _open_gaps(gaps: list[dict[str, Any]], concept: str, group: list[dict[str, Any]]) -> list[str]:
    """The newest run's gaps for one section that no finding fills: a field gap always, a concept gap when empty."""
    out = []
    for g in gaps:
        if g.get("concept") != concept:
            continue
        year = g.get("fiscal_year")
        if not g.get("field") and any(not year or f.get("fiscal_year") == year for f in group):
            continue
        what = _join(g.get("field"), year) or "anything"
        out.append(f"- {_GAP_LABELS.get(g.get('reason'), g.get('reason'))} · {what}: {' '.join(g['detail'].split())}")
    return out


_TAG_SUFFIX = re.compile(r" \((?:under|a theme in) [^)]*\)$")


def _labels(field: str, codes: Any) -> str | None:
    words = [_TAG_SUFFIX.sub("", VOCABULARY[field].get(c, c)) for c in codes or []]
    return ", ".join(words) or None


def _program_details(p: dict[str, Any], findings: list[dict[str, Any]]) -> list[tuple[str, str | None]]:
    """What a programme is, who it is for, and the places, funders, money and results tied to it by name."""
    name = _norm(p.get("name"))
    linked = [f for f in findings if f is not p and name and _norm(f.get("program_name")) == name]

    def lines(*concepts: str) -> str | None:
        return "; ".join(headline(f) + (f" ({f['fiscal_year']})" if f.get("fiscal_year") else "")
                         for f in linked if f.get("concept") in concepts) or None

    return [
        ("Description", p.get("description")),
        ("Themes", _labels("themes", p.get("themes"))),
        ("For", _labels("populations", p.get("populations"))),
        ("Approach", _labels("lenses", p.get("lenses"))),
        ("Tagged from", p.get("tag_note")),
        ("Where", lines("footprint", "org_location")),
        ("Funded by", lines("partner")),
        ("Spend", lines("programme_spend", "csr_spend")),
        ("Results", lines("metric")),
    ]


_STATE_LABELS = {
    "written": "Saved in Sangam", "confirms": "Sangam already holds this", "waiting": "Waiting for a person",
    "conflicts": "Sangam holds another value; a person decides", "kept": "A person kept Sangam's value",
    "skipped": "A person skipped it", "held": "Not saved", "no column": "Sangam has no field for it yet",
}
NOT_IN_SANGAM = frozenset({"waiting", "conflicts", "held", "no column"})


def _state_line(state: dict[str, Any]) -> str:
    label = _STATE_LABELS.get(state.get("state"), state.get("state") or "")
    bits = [label, state.get("row"), state.get("reason")]
    return "  - In Sangam: " + " · ".join(" ".join(str(b).split()) for b in bits if b)


def entity_markdown(rows: dict[str, Any] | list[dict[str, Any]], prior: str | None = None,
                    unplaced: list[dict[str, Any]] = (), states: dict[str, dict[str, Any]] | None = None) -> str:
    """One organisation's brief: the `prior` brief's facts with every research row merged in; the newest row leads.
    `states` is what a save did with each fact, by its fact_key; a fact keeps its last state until promoted again."""
    rows = sorted([rows] if isinstance(rows, dict) else rows,
                  key=lambda r: (str(r.get("researched_on")), str(r.get("researched_at") or "")))
    row = rows[-1]
    held, held_unplaced = record(prior)
    private = any(is_private_source(f.get("source_url")) for f in _findings(row))
    findings = [f for f in merge_findings(rows, held) if not is_private_source(f.get("source_url"))]
    if states:
        findings = [{**f, STATE: states[k]} if (k := json.dumps(list(fact_key(f)))) in states else f
                    for f in findings]
    unplaced = _merge_unplaced(held_unplaced, unplaced)
    gaps = _json_list(row.get("gaps")) if row.get("status") != "wrong_entity" else []
    out = [
        f"# {row['canonical_name'] or row['entity_name']}",
        "",
        STAMP,
        "",
        f"Researched {row['researched_on']} · status **{row['status']}**"
        + (f" · {row['stopped_reason']}" if row["stopped_reason"] else ""),
        "",
        PRIVATE_NOTE if private else row["summary"],
        "",
    ]
    website = next((r["website"] for r in reversed(rows) if r.get("website")), None)
    if website:
        out += [f"Website: {website}", ""]
    if row.get("goals"):
        goals = row["goals"] if isinstance(row["goals"], list) else json.loads(row["goals"])
        if goals:
            out += ["## What it set out to find", ""]
            out += [f"- {g}" for g in goals]
            out.append("")
    if findings and any(r.get("schema_version", 1) < TYPED_SINCE for r in rows):
        out += [
            ("> Some of this was researched under an earlier finding shape, which has no typed fields "
             "to map to columns. It is readable here but cannot be promoted — re-run the research "
             "to put it in the catalog."),
            "",
        ]

    order = ORDER.get(row.get("entity_kind") or "", ())
    present = {f.get("concept") for f in findings}
    titles = {c: CONCEPT_TITLES[c] for c in order}
    titles |= {c: t for c, t in {**CONCEPT_TITLES, **LEGACY_TITLES}.items() if c in present and c not in titles}
    for concept, title in titles.items():
        group = [f for f in findings if f.get("concept") == concept]
        out += [f"## {title}", ""]
        open_gaps = _open_gaps(gaps, concept, group)
        if not group:
            out += [*(open_gaps or ["Not recorded."]), ""]
            continue
        for f in sorted(group, key=lambda f: (f.get("fiscal_year") or "", headline(f))):
            year = f" ({f['fiscal_year']})" if f.get("fiscal_year") else ""
            flag = "" if f.get("basis", "explicit") == "explicit" else f" _{f['basis']}_"
            out.append(f"- **{headline(f)}**{year}{flag}")
            out.append(f"  > {f['evidence']}")
            out.append(
                f"  <sub>{', '.join(b for b in (f.get('source_name') or 'source', f.get('page')) if b)} · {f['source_url']} · "
                f"confidence {f.get('confidence', 'unknown')}</sub> {_block('fact', f)}"
            )
            if f.get(STATE):
                out.append(_state_line(f[STATE]))
            if concept == "document" and f.get("summary"):
                out.append(f"  - Summary: {' '.join(f['summary'].split())}")
            if concept == "program":
                out += [f"  - {label}: {' '.join(str(v).split())}"
                        for label, v in _program_details(f, findings) if v]
        out += [*(["", *open_gaps] if open_gaps else []), ""]

    if unplaced:
        out += ["## Stated, but Sangam has no field for it", ""]
        for u in unplaced:
            out += [f"- **{u['field']}: {' '.join(str(u['value']).split())}**", f"  > {u['evidence']}",
                    (f"  <sub>{', '.join(b for b in ('source', u.get('page')) if b)} · {u['source_url']} · "
                     f"confidence unknown</sub> {_block('unplaced', u)}")]
        out.append("")

    waiting = [f for f in findings if (f.get(STATE) or {}).get("state") in NOT_IN_SANGAM]
    if waiting:
        out += ["## Not in Sangam yet", ""]
        out += [f"- {headline(f)}{f' ({y})' if (y := f.get('fiscal_year')) else ''}: "
                f"{_state_line(f[STATE]).removeprefix('  - In Sangam: ')}" for f in waiting]
        out.append("")

    if len(rows) > 1:
        out += ["## Research runs", ""]
        out += [f"- {r['researched_on']} · {r['status']} · {len(_findings(r))} findings" for r in reversed(rows)]
        out.append("")
    missing = [c for c in row["not_found"] or [] if c not in present]
    if missing:
        names = ", ".join({**CONCEPT_TITLES, **LEGACY_TITLES}.get(c, c).lower() for c in missing)
        out += ["## Looked for, not found", "",
                f"{names}. Not recorded is not the same as not existing.", ""]
    public_sources = list(dict.fromkeys(
        u for r in rows for u in r["sources_read"] or [] if not is_private_source(u)))
    if public_sources:
        out += ["## Sources read", ""]
        out += [f"- {u}" for u in public_sources]
        out.append("")
    out += ["---", "",
            ("_Findings, not catalog rows. A fact here is something a source said, with the "
             "sentence that says it; putting it in the catalog is a separate step._")]
    return "\n".join(out) + "\n"


async def publish_markdown(slug: str, markdown: str) -> str | None:
    """Put a rendered brief in the bucket, where the funder page links it.

    `replace=True` because the key is an identity: re-researching an entity
    rewrites its brief rather than adding a second one. A no-op returning None
    when Storage is not configured.
    """
    return await storage.upload(
        storage.SOURCE_ARCHIVE, storage.brief_key(slug),
        markdown.encode("utf-8"), "text/markdown", replace=True,
    )


async def build(rows: dict[str, Any] | list[dict[str, Any]], unplaced: list[dict[str, Any]] = (),
                states: dict[str, dict[str, Any]] | None = None) -> str:
    """The published brief with these rows merged in. Raises when the brief could not be read, never overwriting it."""
    rows = [rows] if isinstance(rows, dict) else rows
    prior = await storage.read(storage.SOURCE_ARCHIVE, storage.brief_key(rows[0]["slug"]))
    return entity_markdown(rows, prior.decode("utf-8") if prior else None, unplaced, states)


async def publish(rows: dict[str, Any] | list[dict[str, Any]], unplaced: list[dict[str, Any]] = (),
                  states: dict[str, dict[str, Any]] | None = None) -> str | None:
    """Merge a slug's research rows into its brief and publish it. Returns the key, or None."""
    rows = [rows] if isinstance(rows, dict) else rows
    return await publish_markdown(rows[0]["slug"], await build(rows, unplaced, states))


async def promotable(row: dict[str, Any], rows: list[dict[str, Any]]) -> dict[str, Any]:
    """The newest row as promotion reads it: every fact the brief holds or would hold once these rows are merged,
    plus the row's own private findings, which the brief never holds."""
    prior = await storage.read(storage.SOURCE_ARCHIVE, storage.brief_key(row["slug"]))
    facts, unplaced = record(prior.decode("utf-8") if prior else None)
    merged = merge_findings(rows or [row], [{k: v for k, v in f.items() if k != STATE} for f in facts])
    # A pre-typed fact has no concept, so nothing could write it.
    public = [f for f in merged if f.get("concept") and not is_private_source(f.get("source_url"))]
    private = [f for f in _findings(row) if is_private_source(f.get("source_url"))]
    return {**row, "findings": [*public, *private], "unplaced": unplaced}


async def rows_for(conn: Any, slug: str) -> list[dict[str, Any]]:
    """Every research row for one slug, oldest first: what a brief is rendered from."""
    return [dict(r) for r in await (await conn.execute(
        "SELECT * FROM entity_research WHERE slug = %s ORDER BY researched_on, researched_at", (slug,)
    )).fetchall()]
