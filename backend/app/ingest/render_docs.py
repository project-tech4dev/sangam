"""Render docs/ from the research table. Runs on the HOST, never in the container.

The backend image mounts only app/, seed/ and db/, so a process inside it cannot
write a repo file — and should not: these are reviewed artifacts. This reads the
database and writes markdown, the way `make evals` runs pytest on the host venv.

Two kinds of file:
  docs/entities/<slug>.md          one per researched organisation, fully generated
  docs/clients/<ngo>/README.md     hand-written analysis, with generated blocks
                                   between <!-- generated:x --> markers

Text outside a marker is never touched, because a generator cannot write the
reading that makes a client file worth having.
"""

from __future__ import annotations

import asyncio
import json
import os
import re
import sys
from pathlib import Path
from typing import Any

import psycopg
from psycopg.rows import dict_row

from app.ingest.research_records import SCHEMA_VERSION, to_inr

REPO = Path(__file__).resolve().parents[3]
ENTITIES = REPO / "docs" / "entities"
CLIENTS = REPO / "docs" / "clients"

CONCEPT_TITLES = {
    "identity": "Identity",
    "identifier": "Registrations and identifiers",
    "csr_year": "CSR position by year",
    "csr_spend": "Project and sector spend",
    "footprint": "Where the work ran",
    "stated_geography": "Where it says it prioritises",
    "partner": "Implementing partners",
    "program": "Programmes",
    "grant": "Grants",
    "metric": "Reach and outcomes",
    "contact": "Contacts",
    "document": "Source documents",
}
STAMP = "<!-- Generated by `make client-docs`. Do not edit inside the markers. -->"


def marker(name: str) -> tuple[str, str]:
    return f"<!-- generated:{name} -->", "<!-- /generated -->"


def replace_block(text: str, name: str, body: str) -> str:
    """Swap what is between one pair of markers, leaving everything else alone."""
    start, end = marker(name)
    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.DOTALL)
    block = f"{start}\n{body.rstrip()}\n{end}"
    if pattern.search(text):
        return pattern.sub(lambda _: block, text)
    return text.rstrip() + "\n\n" + block + "\n"


def _crore(value: Any) -> str:
    """INR is what we store; crore is what a reader thinks in."""
    try:
        n = float(value)
    except (TypeError, ValueError):
        return str(value)
    return f"₹{n / 10_000_000:,.2f} cr" if n >= 10_000_000 else f"₹{n:,.0f}"


def _money(m: dict[str, Any] | None) -> str | None:
    """A Money finding, printed as the source wrote it and as INR."""
    inr = to_inr(m)
    if inr is None:
        return None
    return f"{_crore(inr)} ({m['text']})"


def _place(f: dict[str, Any]) -> str | None:
    bits = [b for b in (f.get("district"), f.get("state")) if b]
    return ", ".join(bits) or None


_EVIDENCE = frozenset({"concept", "evidence", "source_url", "source_name", "confidence", "basis"})


def _join(*bits: Any) -> str:
    return " · ".join(str(b) for b in bits if b)


def headline(f: dict[str, Any]) -> str:
    """One line per finding, from the typed fields of its concept."""
    # A v1 finding is a flat label/value pair and has no typed fields to read.
    # extra="forbid" means a v2 finding can never carry a label, so this is an
    # exact test of which shape arrived, not a guess.
    if "label" in f:
        return _join(f.get("label"), f.get("value"))
    concept = f.get("concept")
    if concept == "identity":
        return _join(f.get("name"), f.get("funder_type"), f.get("website"),
                     f"part of {f['parent_name']}" if f.get("parent_name") else None)
    if concept == "identifier":
        return f"{f['id_type'].upper()} {f['id_value']}"
    if concept == "csr_year":
        money = {k: _money(f.get(k)) for k in
                 ("prescribed_csr", "total_spent", "spent_on_projects", "average_net_profit",
                  "unspent_transferred", "excess_spent", "admin_overheads",
                  "impact_assessment_cost")}
        return _join(*(f"{k.replace('_', ' ')} {v}" for k, v in money.items() if v)) or "recorded"
    if concept == "csr_spend":
        what = f.get("project_name") or f.get("sector") or "aggregate"
        count = f"{f['project_count']} projects" if f.get("project_count") else None
        return _join(what, _money(f.get("amount")), _place(f), count,
                     f.get("implementing_agency"))
    if concept == "footprint":
        return _join(_place(f) or f.get("name_as_printed"), f.get("program_name"))
    if concept == "stated_geography":
        return _join(_place(f), f.get("role"))
    if concept == "partner":
        return _join(f.get("partner_name"), f.get("partner_kind"), f.get("program_name"))
    if concept == "program":
        return _join(f.get("name"), f.get("kind"),
                     f"under {f['parent_name']}" if f.get("parent_name") else None)
    if concept == "grant":
        return _join(f.get("recipient_name"), f.get("title"), _money(f.get("amount")),
                     f.get("status"))
    if concept == "metric":
        value = _join(f.get("value") if f.get("value") is not None else None, f.get("unit"))
        return _join(f.get("name"), value,
                     f"target {f['target']}" if f.get("target") is not None else None,
                     f.get("stage"), f.get("period"), _place(f))
    if concept == "contact":
        return _join(f.get("name"), f.get("role"), f.get("kind"))
    if concept == "document":
        return _join(f.get("title"), f.get("doc_type"), f.get("as_of"))
    return _join(*(v for k, v in f.items() if k not in _EVIDENCE and v is not None))


def entity_markdown(row: dict[str, Any]) -> str:
    findings = row["findings"] if isinstance(row["findings"], list) else json.loads(row["findings"])
    out = [
        f"# {row['canonical_name'] or row['entity_name']}",
        "",
        STAMP,
        "",
        f"Researched {row['researched_on']} · status **{row['status']}**"
        + (f" · {row['stopped_reason']}" if row["stopped_reason"] else ""),
        "",
        row["summary"],
        "",
    ]
    if row["website"]:
        out += [f"Website: {row['website']}", ""]
    if row.get("goals"):
        goals = row["goals"] if isinstance(row["goals"], list) else json.loads(row["goals"])
        if goals:
            out += ["## What it set out to find", ""]
            out += [f"- {g}" for g in goals]
            out.append("")
    if findings and row.get("schema_version", 1) < SCHEMA_VERSION:
        out += [
            ("> Researched under an earlier finding shape, which has no typed fields to map "
             "to columns. It is readable here but cannot be promoted — re-run the research "
             "to put it in the catalog."),
            "",
        ]

    for concept, title in CONCEPT_TITLES.items():
        group = [f for f in findings if f.get("concept") == concept]
        if not group:
            continue
        out += [f"## {title}", ""]
        for f in sorted(group, key=lambda f: (f.get("fiscal_year") or "", headline(f))):
            year = f" ({f['fiscal_year']})" if f.get("fiscal_year") else ""
            flag = "" if f.get("basis", "explicit") == "explicit" else f" _{f['basis']}_"
            out.append(f"- **{headline(f)}**{year}{flag}")
            out.append(f"  > {f['evidence']}")
            out.append(
                f"  <sub>{f.get('source_name') or 'source'} · {f['source_url']} · "
                f"confidence {f.get('confidence', 'unknown')}</sub>"
            )
        out.append("")

    if row["not_found"]:
        missing = ", ".join(CONCEPT_TITLES.get(c, c).lower() for c in row["not_found"])
        out += ["## Looked for, not found", "",
                f"{missing}. Not recorded is not the same as not existing.", ""]
    if row["sources_read"]:
        out += ["## Sources read", ""]
        out += [f"- {u}" for u in row["sources_read"]]
        out.append("")
    out += ["---", "",
            ("_Findings, not catalog rows. A fact here is something a source said, with the "
             "sentence that says it; putting it in the catalog is a separate step._")]
    return "\n".join(out) + "\n"


def client_block(rows: list[dict[str, Any]]) -> str:
    if not rows:
        return "_No organisation has been researched for this client yet._"
    lines = ["| Organisation | Researched | Status | Facts | Detail |", "|---|---|---|---|---|"]
    for r in rows:
        lines.append(
            f"| {r['canonical_name'] or r['entity_name']} | {r['researched_on']} | "
            f"{r['status']} | {r['fact_count']} | "
            f"[entity file](../../entities/{r['slug']}.md) |"
        )
    return "\n".join(lines)


async def main() -> int:
    url = os.environ.get("DATABASE_URL", "")
    if not url:
        print("DATABASE_URL is not set", file=sys.stderr)
        return 1
    async with await psycopg.AsyncConnection.connect(url, row_factory=dict_row) as conn:
        # The newest row per slug: re-researching an entity supersedes, it does
        # not append a second file.
        rows = await (
            await conn.execute(
                "SELECT DISTINCT ON (slug) * FROM entity_research "
                "ORDER BY slug, researched_at DESC"
            )
        ).fetchall()
        # Names for the index, when the catalog happens to know them.
        named = {
            r["slug"]: r["name"]
            for r in await (await conn.execute("SELECT slug, name FROM orgs")).fetchall()
        }

    # Which clients exist is decided by the repo, not the catalog: a client file
    # is hand-written and committed, and an empty database must not make it
    # disappear from the index.
    clients = [
        {"slug": d.name, "name": named.get(d.name, d.name.replace("-", " ").title())}
        for d in sorted(CLIENTS.iterdir())
        if d.is_dir() and (d / "README.md").exists()
    ]

    ENTITIES.mkdir(parents=True, exist_ok=True)
    for row in rows:
        (ENTITIES / f"{row['slug']}.md").write_text(entity_markdown(row), encoding="utf-8")
    print(f"docs/entities: {len(rows)} file(s)")

    # Every researched funder is shown to every client for now: which funders
    # matter to which NGO is a matching question, and matching is not built.
    funders = [r for r in rows if r["entity_kind"] != "org"]
    written = 0
    for client in clients:
        readme = CLIENTS / client["slug"] / "README.md"
        if not readme.exists():
            continue
        text = readme.read_text(encoding="utf-8")
        readme.write_text(replace_block(text, "funders", client_block(funders)), encoding="utf-8")
        written += 1
    print(f"docs/clients: refreshed {written} client file(s)")

    index = ["| Client | Status |", "|---|---|"]
    for client in clients:
        if (CLIENTS / client["slug"] / "README.md").exists():
            index.append(f"| [{client['name']}]({client['slug']}/README.md) | "
                         f"{len(funders)} funders researched |")
    idx = CLIENTS / "README.md"
    if idx.exists() and len(index) > 2:
        idx.write_text(replace_block(idx.read_text(encoding="utf-8"), "index", "\n".join(index)),
                       encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
